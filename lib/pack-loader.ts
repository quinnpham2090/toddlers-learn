export function getJourneyStopSkills(profileId: string = DEFAULT_PROFILE_ID): SkillRecord[] {
  const skills = getSkills(profileId);
  const byId = new Map(skills.map((skill) => [skill.id, skill]));
  const visited = new Set<string>();
  const order: SkillRecord[] = [];
  const queue: string[] = skills
    .filter((skill) => skill.is_entry_skill)
    .map((skill) => skill.id);
  while (queue.length > 0) {
    const id = queue.shift();
    if (id === undefined || visited.has(id)) {
      continue;
    }
    visited.add(id);
    const skill = byId.get(id);
    if (!skill) {
      continue;
    }
    order.push(skill);
    for (const nextId of skill.next_skills) {
      queue.push(nextId);
    }
  }
  for (const skill of skills) {
    if (!visited.has(skill.id)) {
      order.push(skill);
    }
  }
  return order;
}

